export function getLatestArticles(limit?: number): Article[] {
  const sorted = [...MOCK_ARTICLES].sort(
    (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
  return typeof limit === "number" ? sorted.slice(0, limit) : sorted;
}

export function getArticleBySlug(slug: string): Article | undefined {
  return MOCK_ARTICLES.find((article) => article.slug === slug);
}

export function getArticlesByCategory(categorySlug: string): Article[] {
  return getLatestArticles().filter((article) => article.categorySlug === categorySlug);
}

export function getCategoryBySlug(slug: string) {
  return CATEGORIES.find((category) => category.slug === slug);
}

export function searchArticles(query: string): Article[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return [];
  return getLatestArticles().filter(
    (article) =>
      article.title.toLowerCase().includes(normalized) ||
      article.excerpt.toLowerCase().includes(normalized)
  );
}
